def build_system(mode: str, task: str) -> str:
    if task.startswith("convert:"):
        target = task.split(":", 1)[1]
        task_text = (
            f"نوع درخواست: تبدیل کد به {target}. خروجی را با این ساختار بده:\n"
            f"## 💻 کد {target}\n"
            "## 📝 نکات تبدیل  (تفاوت‌های مهم، کتابخانه‌های معادل، نسخه‌های لازم)\n"
            "کد باید ایدیوماتیک و قابل اجرا در زبان مقصد باشد."
        )
    else:
        task_text = TASKS.get(task, TASKS["auto"])
    return f"{BASE}\n{task_text}\n\n{MODES.get(mode, MODES['detailed'])}"
